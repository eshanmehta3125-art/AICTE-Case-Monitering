import type { ActionEntry, Bureau, CaseRecord, CaseStatus, DemoState } from "@/types/domain";
import { BUREAUS } from "@/types/domain";

const SAMPLE_OFFICERS = ["Meera Rao", "Arjun Menon", "Kavita Shah", "Sana Iqbal", "Devika Nair", "Rohan Das", "Nikhil Patil"] as const;
const MAX_GENERATED_CASES = 5;
const MAX_HISTORY_PER_CASE = 40;

function safeDateTime(value: string) {
  return Number.isNaN(Date.parse(value)) ? new Date().toISOString() : value;
}

function addDays(date: string, amount: number) {
  const value = new Date(`${date}T12:00:00.000Z`);
  value.setUTCDate(value.getUTCDate() + amount);
  return value.toISOString().slice(0, 10);
}

function eventEntry(sequence: number, caseId: string, at: string, kind: ActionEntry["kind"], summary: string, bureau: Bureau): ActionEntry {
  return {
    id: `sim-${sequence}-${caseId}`,
    at,
    kind,
    summary,
    actor: "Demo event engine",
    bureau,
  };
}

function withEntry(item: CaseRecord, entry: ActionEntry, update: Partial<CaseRecord> = {}): CaseRecord {
  return {
    ...item,
    ...update,
    lastAction: entry.summary,
    lastActionAt: entry.at.slice(0, 10),
    history: [entry, ...item.history].slice(0, MAX_HISTORY_PER_CASE),
  };
}

function touchInstitution(state: DemoState, institutionId: string, day: string): DemoState["institutions"] {
  return state.institutions.map((institution) => institution.id === institutionId
    ? { ...institution, lastActivity: !institution.lastActivity || institution.lastActivity < day ? day : institution.lastActivity }
    : institution);
}

function updateOne(state: DemoState, current: CaseRecord, updated: CaseRecord, sequence: number, at: string): DemoState {
  return {
    ...state,
    cases: state.cases.map((item) => item.id === current.id ? updated : item),
    institutions: touchInstitution(state, current.institutionId, at.slice(0, 10)),
    simulationSequence: sequence,
  };
}

function generateComplaint(state: DemoState, sequence: number, at: string): DemoState | null {
  const generatedCount = state.cases.filter((item) => item.id.startsWith("SIM-")).length;
  if (generatedCount >= MAX_GENERATED_CASES) return null;

  const institution = state.institutions.find((item) => item.permanentId === "DEMO-10024") ?? state.institutions[0];
  if (!institution) return null;
  const occupied = new Set(state.cases.filter((item) => item.institutionId === institution.id && item.status !== "Disposed").map((item) => item.bureau));
  const bureau = BUREAUS.find((item) => !occupied.has(item)) ?? BUREAUS[(generatedCount + 2) % BUREAUS.length];
  const day = at.slice(0, 10);
  const id = `SIM-${new Date(at).getUTCFullYear()}-${String(sequence).padStart(5, "0")}`;
  if (state.cases.some((item) => item.id === id)) return null;
  const officer = SAMPLE_OFFICERS[(sequence * 3) % SAMPLE_OFFICERS.length];
  const summary = "New synthetic complaint received and registered in the demonstration stream.";
  const entry = eventEntry(sequence, id, at, "Received", summary, bureau);
  const nextCase: CaseRecord = {
    id,
    receivedAt: day,
    institutionId: institution.id,
    category: sequence % 2 === 0 ? "Academic coordination" : "Institution casework query",
    bureau,
    officer,
    status: "Pending",
    priority: "Normal",
    lastAction: summary,
    lastActionAt: day,
    expectedDisposalDate: addDays(day, 21),
    description: "A fictional case generated by the local demonstration event engine. This is not a real complaint or an official submission.",
    attachmentNames: [],
    relatedCaseIds: [],
    history: [entry],
  };
  return {
    ...state,
    cases: [...state.cases, nextCase],
    institutions: touchInstitution(state, institution.id, day),
    simulationSequence: sequence,
  };
}

function visibleFollowUp(state: DemoState, sequence: number, at: string): DemoState {
  const institution = state.institutions.find((item) => item.permanentId === "DEMO-10024");
  const target = state.cases.find((item) => item.institutionId === institution?.id && item.status !== "Disposed");
  if (!target) return { ...state, simulationSequence: sequence };
  const summary = "Coordination review refreshed by deterministic demonstration rules; human verification remains required.";
  const entry = eventEntry(sequence, target.id, at, "Coordination", summary, target.bureau);
  return updateOne(state, target, withEntry(target, entry), sequence, at);
}

function detectPotentialOverlap(state: DemoState, sequence: number, at: string): DemoState {
  const target = state.cases.find((item) => item.status !== "Disposed" && state.cases.some((other) => other.id !== item.id && other.institutionId === item.institutionId && other.bureau !== item.bureau && other.status !== "Disposed"));
  if (!target) return visibleFollowUp(state, sequence, at);
  const summary = "Potential cross-Bureau overlap detected using a shared institution identity; human review required. No records were merged and no case status changed.";
  const entry = eventEntry(sequence, target.id, at, "Overlap detection", summary, target.bureau);
  return updateOne(state, target, withEntry(target, entry), sequence, at);
}

/**
 * Apply exactly one deterministic synthetic event to the canonical demo case state.
 * Replaying a sequence is idempotent; histories and new-case growth are bounded.
 */
export function simulateDemoEvent(state: DemoState, sequence: number, occurredAt: string): DemoState {
  if (!Number.isSafeInteger(sequence) || sequence <= state.simulationSequence) return state;
  const at = safeDateTime(occurredAt);
  const day = at.slice(0, 10);
  const slot = (sequence - 1) % 9;
  if (slot === 0) return generateComplaint(state, sequence, at) ?? visibleFollowUp({ ...state, simulationSequence: sequence - 1 }, sequence, at);
  if (slot === 8) return detectPotentialOverlap(state, sequence, at);

  const open = state.cases.filter((item) => item.status !== "Disposed");
  const target = open.length ? open[(sequence * 7) % open.length] : state.cases[sequence % Math.max(state.cases.length, 1)];
  if (!target) return { ...state, simulationSequence: sequence };

  const currentStatus = target.status;
  let summary: string;
  let kind: ActionEntry["kind"];
  let update: Partial<CaseRecord> = {};
  switch (slot) {
    case 1: {
      const status: CaseStatus = currentStatus === "Pending" ? "Under process" : currentStatus;
      summary = status !== currentStatus ? "Bureau review started; case moved from Pending to Under process." : `Review checkpoint recorded; status remains ${currentStatus}.`;
      kind = status !== currentStatus ? "Status update" : "Review";
      update = { status };
      break;
    }
    case 2: {
      const nextOfficer = SAMPLE_OFFICERS.find((officer) => officer !== target.officer) ?? SAMPLE_OFFICERS[0];
      summary = `Synthetic assignment updated to ${nextOfficer}.`;
      kind = "Assignment";
      update = { officer: nextOfficer };
      break;
    }
    case 3: {
      const bureau = BUREAUS.find((item) => item !== target.bureau) ?? target.bureau;
      summary = `Synthetic case transferred from ${target.bureau} to ${bureau}.`;
      kind = "Transfer";
      update = { bureau, status: "Transferred", awaitingBureau: undefined };
      break;
    }
    case 4: {
      const offset = sequence % 2 === 0 ? -2 : 3;
      const expected = addDays(day, offset);
      summary = offset < 0
        ? `Demonstration expected date moved to ${expected}; an overdue alert may require review.`
        : `Demonstration expected date moved to ${expected}; approaching-date watch is active.`;
      kind = "Deadline update";
      update = { expectedDisposalDate: expected };
      break;
    }
    case 5: {
      const awaitingBureau = BUREAUS.find((item) => item !== target.bureau) ?? target.bureau;
      summary = `Coordination request recorded; awaiting a response from ${awaitingBureau}.`;
      kind = "Coordination";
      update = { awaitingBureau };
      break;
    }
    case 6:
      summary = "Synthetic case escalated for demonstration review.";
      kind = "Escalation";
      update = { status: "Escalated" };
      break;
    case 7:
      summary = "Synthetic case marked Disposed in the demonstration stream; no official record changed.";
      kind = "Status update";
      update = { status: "Disposed", awaitingBureau: undefined };
      break;
    default:
      summary = "Action note recorded by the demonstration event engine.";
      kind = "Note";
  }

  const entry = eventEntry(sequence, target.id, at, kind, summary, update.bureau ?? target.bureau);
  return updateOne(state, target, withEntry(target, entry, update), sequence, at);
}
